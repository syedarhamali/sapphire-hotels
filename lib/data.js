export function bookingUrl({ checkIn, checkOut, guests } = {}) {
  const url = new URL(hotel.booking);
  url.searchParams.set("locale", "en");
  url.searchParams.set("referrer", "canvas");
  if (checkIn) url.searchParams.set("check_in_date", checkIn);
  if (checkOut) url.searchParams.set("check_out_date", checkOut);
  if (guests) url.searchParams.set("number_adults", String(guests));
  return url.toString();
}

